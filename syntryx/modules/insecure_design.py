from rich.console import Console
from syntryx.core.reporter import Reporter
from urllib.parse import urlparse

console = Console()

async def run(requester, urls: list, forms: list, reporter: Reporter):
    console.print("\n[bold blue]Running Insecure Design checks (assisted)...[/bold blue]")

    # 1. Detect forms that may rely on client-side controls only
    for form in forms:
        inputs = form.get("inputs", [])
        input_names = [(i.get("name") or "").lower() for i in inputs]
        input_types = [(i.get("type") or "").lower() for i in inputs]

        # Common sensitive actions that should have strong server-side controls
        sensitive_keywords = [
            "price", "amount", "quantity", "qty", "total", "discount",
            "role", "admin", "permission", "credit", "balance", "transfer"
        ]

        if any(any(k in name for k in sensitive_keywords) for name in input_names):
            reporter.add_finding(
                module="Insecure Design",
                title="Potential Client-Side Trust Issue",
                severity="medium",
                url=form.get("action", "unknown"),
                description=(
                    "A form contains fields that influence business-critical values "
                    "(price, quantity, role, etc.). Verify that all validation and "
                    "authorization are enforced on the server side, not only in the browser."
                ),
                evidence=f"Inputs: {input_names}"
            )

    # 2. Detect possible missing rate limiting indicators (very basic heuristic)
    login_related = False
    for form in forms:
        input_types = [(i.get("type") or "").lower() for i in form.get("inputs", [])]
        if "password" in input_types:
            login_related = True
            break

    if login_related:
        reporter.add_finding(
            module="Insecure Design",
            title="Login Functionality Detected – Review Rate Limiting",
            severity="info",
            url="N/A",
            description=(
                "Login forms were found. Ensure proper rate limiting, account lockout, "
                "and protection against credential stuffing / brute-force attacks are implemented."
            ),
            evidence="Password field detected in one or more forms."
        )

    # 3. Check for overly descriptive error messages (design smell)
    error_indicators = [
        "stack trace", "exception", "traceback", "sql syntax",
        "oracle error", "mysql error", "postgresql", "odbc",
        "debug", "at line", "file path"
    ]

    for item in urls:
        response = await requester.get(item["url"])
        if not response:
            continue

        body_lower = response.text.lower()
        for indicator in error_indicators:
            if indicator in body_lower:
                reporter.add_finding(
                    module="Insecure Design",
                    title="Verbose Error Message Detected",
                    severity="low",
                    url=item["url"],
                    description=(
                        "The application returned a verbose error message. "
                        "This can leak implementation details and help attackers."
                    ),
                    evidence=f"Indicator found: '{indicator}'"
                )
                break

    # 4. General design review checklist (always added once)
    reporter.add_finding(
        module="Insecure Design",
        title="Manual Secure Design Review Recommended",
        severity="info",
        url="N/A",
        description=(
            "Insecure Design issues require human review. Recommended checks:\n"
            "• Are business rules enforced on the server?\n"
            "• Is there proper separation of duties?\n"
            "• Are there abuse cases / rate limits for sensitive actions?\n"
            "• Is trust boundary clearly defined between client and server?\n"
            "• Are multi-step processes protected against step skipping?"
        ),
        evidence="This is a design-level checklist generated by Syntryx."
    )

    console.print("[green]Insecure Design checks completed.[/green]")
